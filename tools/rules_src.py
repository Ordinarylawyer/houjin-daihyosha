def VQ(tp, code, cond, keys, order=80, extra=None, text="代表者の状況を選んでください。"):
    ch = []
    for k in keys:
        if extra and k in extra:
            ch.append((k, extra[k]))
        else:
            ch.append((k, VQ_LABEL[k]))
    Q(tp, code, order, text, ch, cond,
      help="ほとんどの事件は「通常」です。代表者の欠員・職務代行者の選任は登記事項証明書で確認できます。")


