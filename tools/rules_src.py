def CH_COMMITTEE(code, pri, t, cname, head, basis, head_basis, x=True, note="", verified=True, extra_cond=""):
    """委員会が代表者になる場合。委員会の行の次に「同委員会代表者（委員長等）」の行を置く。"""
    rep = f"{cname}（{cname}を代表する{head}）"
    both = f"{basis}、{head_basis}、{CH_BASIS_ADM}"
    t_same = "{地位}　{法人名}\n同代表者兼処分行政庁　{法人名}" + cname + "\n同委員会代表者{資格}　{氏名}"
    t_sep = "{地位}　{法人名}\n同代表者　{法人名}" + cname + "\n同委員会代表者{資格}　{氏名}" + \
            "\n処分行政庁　（処分行政庁名）\n　　　　　　（処分行政庁の氏名）"
    nt = (note + " " if note else "") + NOTE_DUAL
    if x:
        R("CH", code + "1", pri, f"T={t};X=Y", rep, head, both, tmpl=t_same, note=nt, verified=verified)
        R("CH", code + "2", pri + 1, f"T={t};X=N", rep, head, both, tmpl=t_sep, note=nt, verified=verified)
    else:
        R("CH", code + "1", pri, f"T={t}", rep, head, both, tmpl=t_same, note=nt, verified=verified)


