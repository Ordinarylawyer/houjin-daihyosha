def T(code, name, group, law, order, desc=""):
    TYPES.append(dict(code=code, name=name, group=group, law=law, order=order, desc=desc))


def _expand(tp, cond):
    """"S=N;T=D || S=L" → "KK-S=N;KK-T=D||KK-S=L"（|| は「又は」。質問の表示条件だけで使う）"""
    if not cond:
        return ""
    groups = []
    for g in cond.split("||"):
        out = []
        for c in g.split(";"):
            c = c.strip()
            if not c:
                continue
            k, v = c.split("=", 1)
            out.append(f"{tp}-{k.strip()}={v.strip()}")
        groups.append(";".join(out))
    return "||".join(groups)


def Q(tp, code, order, text, choices, cond="", help=""):
    QUESTIONS.append(dict(
        code=f"{tp}-{code}", type=tp, order=order, text=text, help=help,
        choices="|".join(f"{k}={v}" for k, v in choices), cond=_expand(tp, cond)))


def R(tp, code, pri, cond, rep, title, basis, tmpl=TPL_STD, docs="", note="",
      kind="代表者", verified=True, vdate="2026-11-19"):
    RULES.append(dict(
        code=f"{tp}-{code}", type=tp, pri=pri, cond=_expand(tp, cond), rep=rep,
        title=title, basis=basis, tmpl=tmpl, docs=docs, note=note, kind=kind,
        verified=f"確認済（{vdate}）" if verified else "要確認"))


